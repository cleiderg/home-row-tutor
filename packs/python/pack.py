"""Python syntax: a typed tour of the language, from print to classes.

Task fields are described in SPEC.md. `starter` text with ____ is a faded
example: the learner fills the blanks. `checkpoint` tasks are unaided.
"""


def T(id, title, concept, lesson, example, prompt, tests, solution, hints=(), **kw):
    return dict(id=id, title=title, concept=concept, lesson=lesson, example=example,
                prompt=prompt, tests=tests, solution=solution, hints=list(hints), **kw)


def CP(id, title, prompt, tests, solution, **kw):
    return T(id, title, "unaided checkpoint", "", "", prompt, tests, solution, checkpoint=True, **kw)


