"""Vim keybindings: motions, operators, text objects, search, and macros.

Each task starts from `start` with the cursor at `cursor` [line, column]
(line from 1, column from 0) and is solved when the buffer and/or cursor match
`goal`. `solution` is a key sequence; par is its keystroke count.
"""


def T(id, title, concept, lesson, example, prompt, start, cursor, goal, solution, hints=(), **kw):
    return dict(id=id, title=title, concept=concept, lesson=lesson, example=example, prompt=prompt,
                start=start, cursor=cursor, goal=goal, solution=solution, hints=list(hints), **kw)


def CP(id, title, prompt, start, cursor, goal, solution, **kw):
    return T(id, title, "unaided checkpoint", "", "", prompt, start, cursor, goal, solution, checkpoint=True, **kw)


