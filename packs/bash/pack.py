"""Bash: the everyday command line, typed one command at a time.

Each task runs the learner's commands in a fresh temporary directory holding
`files`. `expect` says what is checked afterwards (see SPEC.md).
"""


def T(id, title, concept, lesson, example, prompt, expect, solution, hints=(), files=None, **kw):
    return dict(id=id, title=title, concept=concept, lesson=lesson, example=example, prompt=prompt,
                expect=expect, solution=solution, hints=list(hints), files=files or {}, **kw)


def CP(id, title, prompt, expect, solution, files=None, **kw):
    return T(id, title, "unaided checkpoint", "", "", prompt, expect, solution, files=files, checkpoint=True, **kw)


